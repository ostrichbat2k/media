#define ERROR_STRING_BUFFER_LENGTH 256

// Output format corresponding to AudioFormat.ENCODING_PCM_16BIT.
static const AVSampleFormat OUTPUT_FORMAT_PCM_16BIT = AV_SAMPLE_FMT_S16;
// Output format corresponding to AudioFormat.ENCODING_PCM_FLOAT.
static const AVSampleFormat OUTPUT_FORMAT_PCM_FLOAT = AV_SAMPLE_FMT_FLT;

// LINT.IfChange
static const int AUDIO_DECODER_ERROR_INVALID_DATA = -1;
static const int AUDIO_DECODER_ERROR_OTHER = -2;
// LINT.ThenChange(../java/androidx/media3/decoder/ffmpeg/FfmpegAudioDecoder.java)

// Mirrors androidx.media3.decoder.ffmpeg.FfmpegAudioDecoder's OUTPUT_MODE_* constants.
// LINT.IfChange
// Forces every track down to 16-bit integer PCM regardless of the real source bit depth --
// the original, unconditional behavior for a sink with no wider direct support.
static const jint OUTPUT_MODE_PCM_16BIT = 0;
// Forces decode to 32-bit float -- unchanged from the original "outputFloat" path, still used
// for the normal (non-USB) output path where float genuinely improves quality for a sink that
// supports it directly, independent of the source's own bit depth.
static const jint OUTPUT_MODE_PCM_FLOAT = 1;
// Requests only the narrowest (16-bit) hint and otherwise asks the decoder to keep whatever
// sample format its own decode logic naturally produces for the real source, then has
// swr_convert only ever de-planarize that -- never widen or narrow it. FLAC/ALAC/PCM-style
// lossless decoders already pick their true native sample_fmt from the real stream's own bit
// depth (confirmed by reading libavcodec/flacdec.c's flac_set_bps: it widens to 32-bit only
// when the *real* STREAMINFO bps is >16, independent of what's requested, as long as the
// request itself isn't wider than 16-bit and thus doesn't force an unnecessary widening via its
// own `want32` check). This mode exists specifically for the USB bit-perfect path, where the
// sink (see UsbAudioOutputProvider.kt) can take either 16-bit or 32-bit integer PCM directly and
// we want whichever one exactly matches the file, with no float round-trip at all.
// LINT.ThenChange(../java/androidx/media3/decoder/ffmpeg/FfmpegAudioDecoder.java)
static const jint OUTPUT_MODE_NATIVE_INTEGER = 2;

// Replaces a bare SwrContext* as context->opaque so the per-context requested OUTPUT_MODE_*
// (needed on every decodePacket() call, and across a TrueHD ffmpegReset()) travels alongside
// the lazily-created resampler rather than needing a second out-of-band lookup.
struct DecoderContext {
  SwrContext* resampleContext = nullptr;
  jint outputMode = OUTPUT_MODE_PCM_16BIT;
};

static jmethodID growOutputBufferMethod;

/**
 * Returns the AVCodec with the specified name, or NULL if it is not available.
 */
const AVCodec* getCodecByName(JNIEnv* env, jstring codecName);

/**
 * Allocates and opens a new AVCodecContext for the specified codec, passing the
 * provided extraData as initialization data for the decoder if it is non-NULL.
 * Returns the created context.
 */
AVCodecContext* createContext(JNIEnv* env, const AVCodec* codec,
                              jbyteArray extraData, jint outputMode,
                              jint rawSampleRate, jint rawChannelCount);

struct GrowOutputBufferCallback {
  uint8_t* operator()(int requiredSize) const;

  JNIEnv* env;
  jobject thiz;
  jobject decoderOutputBuffer;
};

/**
 * Decodes the packet into the output buffer, returning the number of bytes
 * written, or a negative AUDIO_DECODER_ERROR constant value in the case of an
 * error.
 */
int decodePacket(AVCodecContext* context, AVPacket* packet,
                 uint8_t* outputBuffer, int outputSize,
                 GrowOutputBufferCallback growBuffer);

/**
 * Transforms ffmpeg AVERROR into a negative AUDIO_DECODER_ERROR constant value.
 */
int transformError(int errorNumber);

/**
 * Outputs a log message describing the avcodec error number.
 */
void logError(const char* functionName, int errorNumber);

/**
 * Releases the specified context.
 */
void releaseContext(AVCodecContext* context);

jint JNI_OnLoad(JavaVM* vm, void* reserved) {
  JNIEnv* env;
  if (vm->GetEnv(reinterpret_cast<void**>(&env), JNI_VERSION_1_6) != JNI_OK) {
    LOGE("JNI_OnLoad: GetEnv failed");
    return -1;
  }
  jclass clazz =
      env->FindClass("androidx/media3/decoder/ffmpeg/FfmpegAudioDecoder");
  if (!clazz) {
    LOGE("JNI_OnLoad: FindClass failed");
    return -1;
  }
  growOutputBufferMethod =
      env->GetMethodID(clazz, "growOutputBuffer",
                       "(Landroidx/media3/decoder/"
                       "SimpleDecoderOutputBuffer;I)Ljava/nio/ByteBuffer;");
  if (!growOutputBufferMethod) {
    LOGE("JNI_OnLoad: GetMethodID failed");
    return -1;
  }
  return JNI_VERSION_1_6;
}

